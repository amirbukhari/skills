import { expect, it } from 'vitest';
import { projects } from '../../declarations/resources/fixtures';
import { renderContractIndex, renderResourceContract } from './schemas';

const contract = renderResourceContract(projects);

it('names the declaration it was generated from on its first line', () => {
  expect(contract.split('\n')[0]).toMatch(/^\/\/ Generated by .*generate:resources from generators\/resources\/work-projects\.ts\. Do not edit by hand\.$/);
});

it('declares an enum once and refers to it from the record, the input and the filter', () => {
  expect(contract).toContain('export const stageSchema = z.enum([\'DRAFT\', \'LIVE\']);');
  expect(contract).toContain('  stage: stageSchema,');
  expect(contract).toContain('  stage: stageSchema.default(\'DRAFT\'),');
  expect(contract).toContain('  stage: stageSchema.optional(),');
});

it('keeps the id and the timestamps out of the input', () => {
  const input = contract.slice(contract.indexOf('export const inputSchema'), contract.indexOf('export const filterSchema'));
  expect(input).not.toMatch(/\b(id|created|modified):/);
  expect(input).toContain('parentId: z.string().uuid().nullable().default(null),');
});

it('exports each contract under its camelCase name', () => {
  expect(renderContractIndex([projects])).toContain('export * as workProjects from \'./work-projects\';');
});
