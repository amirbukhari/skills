import { config } from '../../config';

/** `work-orders` to `workOrders`: the name generated code gives a resource. */
export const camelCase = (kebab: string): string => kebab.replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase());

/** `workOrders` or `work-orders` to `WorkOrders`. */
export const pascalCase = (name: string): string => {
  const camel = camelCase(name);
  return camel.charAt(0).toUpperCase() + camel.slice(1);
};

/** `closeWorkOrder` to `close-work-order`: an action's folder name. */
export const kebabCase = (camel: string): string => camel.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

/** The first line of every generated file: the command that writes it and what it is written from. */
export const generatedHeader = (command: string, source: string): string => (
  `// Generated by ${config.run} ${command} from ${source}. Do not edit by hand.`
);

/** A string literal in generated code. */
export const literal = (value: string | number | boolean): string => (
  typeof value === 'string' ? `'${value.replace(/\\/g, '\\\\').replace(/'/g, '\\\'')}'` : String(value)
);
